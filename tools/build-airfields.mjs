import fs from "fs";

const LAT0 = 50.4501;
const LON0 = 30.5234;
const M_LAT = 111320;
const M_LON = 111320 * Math.cos((LAT0 * Math.PI) / 180);

function chain(parts) {
  const unused = parts.map((w) => w.slice());
  const rings = [];
  const eq = (p, q) => Math.abs(p[0] - q[0]) < 1e-4 && Math.abs(p[1] - q[1]) < 1e-4;
  while (unused.length) {
    let ring = unused.pop();
    for (let guard = 0; guard < 4000; guard++) {
      const a = ring[0];
      const b = ring[ring.length - 1];
      let hit = -1;
      let mode = 0;
      for (let i = 0; i < unused.length; i++) {
        const w = unused[i];
        const c = w[0];
        const d = w[w.length - 1];
        if (eq(b, c)) { hit = i; mode = 1; break; }
        if (eq(b, d)) { hit = i; mode = 2; break; }
        if (eq(a, d)) { hit = i; mode = 3; break; }
        if (eq(a, c)) { hit = i; mode = 4; break; }
      }
      if (hit < 0) break;
      const w = unused.splice(hit, 1)[0];
      if (mode === 1) ring = ring.concat(w.slice(1));
      else if (mode === 2) ring = ring.concat([...w].reverse().slice(1));
      else if (mode === 3) ring = w.concat(ring.slice(1));
      else ring = [...w].reverse().concat(ring.slice(1));
    }
    if (ring.length > 20) rings.push(ring);
  }
  return rings;
}

function inside(ring, lon, lat) {
  let n = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const xi = ring[i][0];
    const yi = ring[i][1];
    const xj = ring[j][0];
    const yj = ring[j][1];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / ((yj - yi) || 1e-12) + xi) n = !n;
  }
  return n;
}

const admin = JSON.parse(fs.readFileSync("tools/cache/kyiv-admin.json", "utf8"));
const zones = [];
for (const rel of admin.elements) {
  const outers = [];
  const inners = [];
  for (const m of rel.members || []) {
    if (!m.geometry) continue;
    const line = m.geometry.map((p) => [p.lon, p.lat]);
    if (m.role === "outer") outers.push(line);
    else if (m.role === "inner") inners.push(line);
  }
  zones.push({ outers: chain(outers), inners: chain(inners) });
}

function inKyiv(lon, lat) {
  if (lat < 49.43 || lat > 51.07 || lon < 29.23 || lon > 32.17) return false;
  return zones.some((z) => z.outers.some((r) => inside(r, lon, lat)) && !z.inners.some((r) => inside(r, lon, lat)));
}

function world(lat, lon) {
  return { x: -((lon - LON0) * M_LON), z: (lat - LAT0) * M_LAT };
}

const runways = JSON.parse(fs.readFileSync("tools/cache/runways.json", "utf8")).elements.map((e) => {
  const g = e.geometry;
  const a = g[0];
  const b = g[g.length - 1];
  const north = (b.lat - a.lat) * M_LAT;
  const east = (b.lon - a.lon) * M_LON;
  const len = Math.hypot(east, north);
  const midLat = (a.lat + b.lat) / 2;
  const midLon = (a.lon + b.lon) / 2;
  return {
    lat: midLat,
    lon: midLon,
    len: Number(e.tags.length) || len,
    wid: Number(e.tags.width) || 30,
    h: -Math.atan2(east, north),
    surface: e.tags.surface || "",
    ref: e.tags.ref || "",
  };
});

const fields = [];
for (const e of JSON.parse(fs.readFileSync("tools/cache/aerodromes.json", "utf8")).elements) {
  const t = e.tags || {};
  const c = e.center || e;
  if (!inKyiv(c.lon, c.lat)) continue;
  const near = runways
    .map((r) => ({ r, d: Math.hypot((r.lat - c.lat) * M_LAT, (r.lon - c.lon) * M_LON) }))
    .filter((x) => x.d < 2200)
    .sort((a, b) => b.r.len - a.r.len);
  const runway = near[0]?.r;
  const pos = world(runway ? runway.lat : c.lat, runway ? runway.lon : c.lon);
  const name = t["name:en"] || t.name || "Airfield";
  fields.push({
    id: (t.icao || name).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""),
    name,
    icao: t.icao || "",
    x: Math.round(pos.x),
    z: Math.round(pos.z),
    h: runway ? Number(runway.h.toFixed(4)) : 0,
    len: Math.round(runway ? runway.len : 700),
    wid: Math.round(runway ? Math.max(18, runway.wid) : 24),
    surface: runway?.surface || (t.disused || t.abandoned ? "grass" : "grass"),
    ref: runway?.ref || "",
  });
}

const seen = new Set();
const unique = [];
for (const f of fields.sort((a, b) => b.len - a.len)) {
  if (seen.has(f.id)) continue;
  if (unique.some((o) => Math.hypot(o.x - f.x, o.z - f.z) < 400)) continue;
  seen.add(f.id);
  unique.push(f);
}
unique.sort((a, b) => a.name.localeCompare(b.name));

const body = `// Generated by tools/build-airfields.mjs from OpenStreetMap (ODbL).
export const FIELDS = ${JSON.stringify(unique, null, 2)};

export function runwayStart(field) {
  const half = Math.max(40, field.len * 0.5 - 50);
  return {
    x: field.x - Math.sin(field.h) * half,
    z: field.z - Math.cos(field.h) * half,
    h: field.h,
  };
}

export function fieldAt(fields, x, z) {
  let best = null;
  let bestD = Infinity;
  for (const f of fields) {
    const along = (x - f.x) * Math.sin(f.h) + (z - f.z) * Math.cos(f.h);
    const lat = (x - f.x) * Math.cos(f.h) - (z - f.z) * Math.sin(f.h);
    if (Math.abs(along) > f.len * 0.5 + 30) continue;
    if (Math.abs(lat) > f.wid * 0.5 + 16) continue;
    if (Math.abs(lat) < bestD) {
      bestD = Math.abs(lat);
      best = f;
    }
  }
  return best;
}

export function nearestField(fields, x, z) {
  let best = fields[0];
  let bestD = Infinity;
  for (const f of fields) {
    const d = Math.hypot(f.x - x, f.z - z);
    if (d < bestD) {
      bestD = d;
      best = f;
    }
  }
  return best;
}
`;
fs.writeFileSync("src/airfields.js", body);
